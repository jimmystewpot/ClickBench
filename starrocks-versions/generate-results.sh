#!/usr/bin/env bash
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${HERE}/.." && pwd)"

OUT="${HERE}/data.generated.js"
QUERIES_FILE="${ROOT}/starrocks/queries.sql"

if [ ! -f "${QUERIES_FILE}" ]; then
    echo "Warning: ${QUERIES_FILE} not found; using fallback queries" >&2
    QUERIES_JSON="[]"
else
    QUERIES_JSON="$(jq -R -s 'split("\n") | map(select(length > 0))' "${QUERIES_FILE}")"
fi

{
    echo '// Generated by starrocks-versions/generate-results.sh. Do not edit.'
    echo "const queries = ${QUERIES_JSON};"
    echo ''
    echo 'const data = ['
    
    FIRST=1
    # Find all JSON results under results/
    while IFS= read -r f; do
        [ -z "$f" ] && continue
        [ ! -f "$f" ] && continue
        
        ENTRY="$(jq --compact-output ". += {\"source\": \"${f#$HERE/}\"}" "$f" 2>/dev/null || true)"
        [ -z "$ENTRY" ] && continue

        [ "$FIRST" -eq 0 ] && echo -n ','
        FIRST=0
        printf '\n%s' "$ENTRY"
    done < <(find "${HERE}/results" -name '*.json' | sort -V)
    
    echo ''
    echo '];'
} > "${OUT}"

echo "Generated ${OUT} ($(wc -c < "${OUT}") bytes)" >&2
